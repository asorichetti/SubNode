#!/usr/bin/env node

/**
 * Selector generator - produces TS and Go outputs from selectors.json
 * 
 * Usage:
 *   node generate-selectors.js              # Generate files
 *   node generate-selectors.js --check      # Check for drift (CI)
 */

const fs = require('fs');
const path = require('path');

const SELECTORS_FILE = path.join(__dirname, 'selectors.json');
const TS_OUTPUT = path.join(__dirname, '../../frontend/src/lib/testids.gen.ts');
const GO_OUTPUT = path.join(__dirname, '../internal/selectors/selectors.gen.go');

// Load selectors
function loadSelectors() {
  return JSON.parse(fs.readFileSync(SELECTORS_FILE, 'utf8'));
}

// Generate TypeScript output
function generateTS(selectors) {
  const lines = [];
  lines.push('// Code generated by generate-selectors.js. DO NOT EDIT.');
  lines.push('// Source: lib/selectors.json');
  lines.push('');
  lines.push('// This file is auto-generated. Do not edit manually.');
  lines.push('export const testids = {');

  for (const [section, items] of Object.entries(selectors)) {
    lines.push(`  ${section}: {`);
    const values = Object.entries(items);
    for (const [key, value] of values) {
      const comma = key === values[values.length - 1][0] ? '' : ',';
      lines.push(`    ${key}: '${value}'${comma}`);
    }
    lines.push('  },');
  }

  lines.push('} as const;');
  lines.push('');
  lines.push('// Helper type inference');
  lines.push('export type Testid = typeof testids[keyof typeof testids] extends infer T ? T extends Record<string, string> ? T[keyof T] : never : never;');
  lines.push('');

  return lines.join('\n');
}

// Generate Go output
function generateGO(selectors) {
  const lines = [];
  lines.push('// Code generated by generate-selectors.js. DO NOT EDIT.');
  lines.push('// Source: lib/selectors.json');
  lines.push('package selectors');
  lines.push('');
  lines.push('// This file is auto-generated. Do not edit manually.');
  lines.push('');
  
  // Helper function to build selectors
  lines.push('func sel(name string) string { return "[data-testid=" + name + "]" }');
  lines.push('');

  // Generate structs and constants
  for (const [section, items] of Object.entries(selectors)) {
    // Struct
    const structName = toPascalCase(section);
    lines.push(`type ${structName}Selectors struct {`);
    for (const [name, value] of Object.entries(items)) {
      const fieldName = toPascalCase(name);
      lines.push(`\t${fieldName} string`);
    }
    lines.push('}');
    lines.push('');

    // Instance variable
    lines.push(`var ${structName} = ${structName}Selectors{`);
    for (const [name, value] of Object.entries(items)) {
      const fieldName = toPascalCase(name);
      lines.push(`\t${fieldName}: sel("${value}"),`);
    }
    lines.push('}');
    lines.push('');
  }

  return lines.join('\n');
}

function toPascalCase(str) {
  return str
    .split(/[-_]/)
    .map(s => s.charAt(0).toUpperCase() + s.slice(1))
    .join('');
}

function main() {
  const args = process.argv.slice(2);
  const checkMode = args.includes('--check');

  const selectors = loadSelectors();
  const tsContent = generateTS(selectors);
  const goContent = generateGO(selectors);

  if (checkMode) {
    // Check for drift
    let hasDrift = false;

    try {
      const existingTS = fs.readFileSync(TS_OUTPUT, 'utf8');
      if (existingTS !== tsContent) {
        console.error('DRIFT: TypeScript file differs from generated');
        hasDrift = true;
      }
    } catch (e) {
      console.error('DRIFT: TypeScript file does not exist or cannot be read');
      hasDrift = true;
    }

    try {
      const existingGO = fs.readFileSync(GO_OUTPUT, 'utf8');
      if (existingGO !== goContent) {
        console.error('DRIFT: Go file differs from generated');
        hasDrift = true;
      }
    } catch (e) {
      console.error('DRIFT: Go file does not exist or cannot be read');
      hasDrift = true;
    }

    if (hasDrift) {
      console.error('\nTo fix drift, run: node generate-selectors.js');
      process.exit(1);
    }

    console.log('OK: No drift detected');
    process.exit(0);
  } else {
    // Generate files
    const tsDir = path.dirname(TS_OUTPUT);
    const goDir = path.dirname(GO_OUTPUT);

    if (!fs.existsSync(tsDir)) fs.mkdirSync(tsDir, { recursive: true });
    if (!fs.existsSync(goDir)) fs.mkdirSync(goDir, { recursive: true });

    fs.writeFileSync(TS_OUTPUT, tsContent);
    fs.writeFileSync(GO_OUTPUT, goContent);

    console.log('Generated:', TS_OUTPUT);
    console.log('Generated:', GO_OUTPUT);
  }
}

main();
